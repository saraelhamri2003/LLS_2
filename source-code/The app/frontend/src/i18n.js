export const makeT = (lang) => (key, vars) => {
  let text = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.split(`{${name}}`).join(String(value));
    });
  }
  return text;
};

// Translate a label that comes from the data (falls back to the original)
export const makeTerm = (lang) => (text) => (lang === 'fr' ? DATA_TERMS_FR[text] || text : text);

export const LangContext = createContext({ lang: 'en', t: makeT('en'), term: makeTerm('en') });
export const useLang = () => useContext(LangContext);
